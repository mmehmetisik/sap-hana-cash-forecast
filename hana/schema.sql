-- Valuation rate: the CBRT buying rate valid on the evening of IV_TARIH.
-- Inverted-date trick: valid-from ≤ T  ⇔  GDATU ≥ inverted(T); the newest has the smallest GDATU.
CREATE FUNCTION TF_KUR (IV_TARIH NVARCHAR(8))
RETURNS TABLE (FCURR NVARCHAR(5), UKURS DECIMAL(9,5))
LANGUAGE SQLSCRIPT SQL SECURITY INVOKER READS SQL DATA AS
BEGIN
  RETURN
    SELECT FCURR, UKURS FROM (
      SELECT FCURR, UKURS, ROW_NUMBER() OVER (PARTITION BY FCURR ORDER BY GDATU ASC) AS SIRA
        FROM TCURR
       WHERE MANDT = '100' AND KURST = 'B' AND TCURR = 'TRY'
         AND GDATU >= TO_NVARCHAR(99999999 - TO_INT(TO_NVARCHAR(
                ADD_DAYS(TO_DATE(:IV_TARIH, 'YYYYMMDD'), 1), 'YYYYMMDD'))))
     WHERE SIRA = 1
    UNION ALL SELECT 'TRY', 1 FROM DUMMY;
END
-- @@
-- Customer (D) and vendor (K) invoices still open on the evening of IV_TARIH.
-- Net due date as in SAP: ZFBDT (baseline date) + ZBD1T (days).
CREATE FUNCTION TF_ACIK_KALEMLER (IV_TARIH NVARCHAR(8))
RETURNS TABLE (KOART NVARCHAR(1), BELNR NVARCHAR(10), GJAHR NVARCHAR(4), MUHATAP NVARCHAR(10),
               XBLNR NVARCHAR(16), BLDAT DATE, NETDT DATE, VADE_GUN INTEGER, WAERS NVARCHAR(5),
               WRBTR DECIMAL(23,2), DMBTR DECIMAL(23,2), TL_DEGER DECIMAL(23,2), GECIKME_GUN INTEGER)
LANGUAGE SQLSCRIPT SQL SECURITY INVOKER READS SQL DATA AS
BEGIN
  LT_KUR = SELECT * FROM TF_KUR(:IV_TARIH);
  LT_KALEM =
    SELECT s.KOART, s.BELNR, s.GJAHR,
           CASE WHEN s.KOART = 'D' THEN s.KUNNR ELSE s.LIFNR END AS MUHATAP,
           k.XBLNR, TO_DATE(k.BLDAT, 'YYYYMMDD') AS BLDAT,
           ADD_DAYS(TO_DATE(s.ZFBDT, 'YYYYMMDD'), s.ZBD1T) AS NETDT,
           TO_INT(s.ZBD1T) AS VADE_GUN, k.WAERS, s.WRBTR, s.DMBTR
      FROM BSEG s
      JOIN BKPF k ON k.MANDT = s.MANDT AND k.BUKRS = s.BUKRS AND k.BELNR = s.BELNR AND k.GJAHR = s.GJAHR
     WHERE s.MANDT = '100' AND s.BUKRS = '1000' AND s.BSCHL IN ('01', '31')
       AND k.BUDAT <= :IV_TARIH
       AND (s.AUGDT = '00000000' OR s.AUGDT > :IV_TARIH);
  RETURN
    SELECT a.KOART, a.BELNR, a.GJAHR, a.MUHATAP, a.XBLNR, a.BLDAT, a.NETDT, a.VADE_GUN, a.WAERS,
           a.WRBTR, a.DMBTR, ROUND(a.WRBTR * r.UKURS, 2) AS TL_DEGER,
           GREATEST(DAYS_BETWEEN(a.NETDT, TO_DATE(:IV_TARIH, 'YYYYMMDD')), 0) AS GECIKME_GUN
      FROM :LT_KALEM a JOIN :LT_KUR r ON r.FCURR = a.WAERS;
END
-- @@
-- Customer payment history, censored data included. Every invoice that fell due in the last
-- IV_GUN days is one observation: if paid, OLAY = 1 and GECIKME = clearing date − due date;
-- if still unpaid, OLAY = 0 and GECIKME = report date − due date ("at least this late").
-- Ignoring unpaid invoices makes late payers look punctual, so they are included.
CREATE FUNCTION TF_ODEME_GECMISI (IV_TARIH NVARCHAR(8), IV_GUN INTEGER)
RETURNS TABLE (KUNNR NVARCHAR(10), GECIKME INTEGER, OLAY INTEGER, YAS_GUN INTEGER, DMBTR DECIMAL(23,2))
LANGUAGE SQLSCRIPT SQL SECURITY INVOKER READS SQL DATA AS
BEGIN
  LT_F =
    SELECT s.KUNNR, s.AUGDT, s.DMBTR, ADD_DAYS(TO_DATE(s.ZFBDT, 'YYYYMMDD'), s.ZBD1T) AS NETDT
      FROM BSEG s
      JOIN BKPF k ON k.MANDT = s.MANDT AND k.BUKRS = s.BUKRS AND k.BELNR = s.BELNR AND k.GJAHR = s.GJAHR
     WHERE s.MANDT = '100' AND s.BUKRS = '1000' AND s.BSCHL = '01' AND k.BUDAT <= :IV_TARIH;
  RETURN
    SELECT KUNNR,
           CASE WHEN AUGDT <> '00000000' AND AUGDT <= :IV_TARIH
                THEN DAYS_BETWEEN(NETDT, TO_DATE(AUGDT, 'YYYYMMDD'))
                ELSE DAYS_BETWEEN(NETDT, TO_DATE(:IV_TARIH, 'YYYYMMDD')) END AS GECIKME,
           CASE WHEN AUGDT <> '00000000' AND AUGDT <= :IV_TARIH THEN 1 ELSE 0 END AS OLAY,
           DAYS_BETWEEN(NETDT, TO_DATE(:IV_TARIH, 'YYYYMMDD')) AS YAS_GUN,
           DMBTR
      FROM :LT_F
     WHERE NETDT <= TO_DATE(:IV_TARIH, 'YYYYMMDD')
       AND NETDT > ADD_DAYS(TO_DATE(:IV_TARIH, 'YYYYMMDD'), -:IV_GUN);
END
-- @@
-- Open receivables aging (TRY, at the report-date FX rate).
CREATE FUNCTION TF_YASLANDIRMA (IV_TARIH NVARCHAR(8))
RETURNS TABLE (KUNNR NVARCHAR(10), NAME1 NVARCHAR(35), WAERS NVARCHAR(5), VADESI_GELMEMIS DECIMAL(23,2),
               GUN_0_30 DECIMAL(23,2), GUN_31_60 DECIMAL(23,2), GUN_61_90 DECIMAL(23,2),
               GUN_90_USTU DECIMAL(23,2), TOPLAM DECIMAL(23,2), KALEM_SAYISI INTEGER)
LANGUAGE SQLSCRIPT SQL SECURITY INVOKER READS SQL DATA AS
BEGIN
  LT_ACIK = SELECT * FROM TF_ACIK_KALEMLER(:IV_TARIH) WHERE KOART = 'D';
  RETURN
    SELECT a.MUHATAP AS KUNNR, m.NAME1, MAX(a.WAERS) AS WAERS,
           SUM(CASE WHEN a.NETDT >= TO_DATE(:IV_TARIH, 'YYYYMMDD') THEN a.TL_DEGER ELSE 0 END) AS VADESI_GELMEMIS,
           SUM(CASE WHEN a.NETDT < TO_DATE(:IV_TARIH, 'YYYYMMDD') AND a.GECIKME_GUN BETWEEN 0 AND 30
                    THEN a.TL_DEGER ELSE 0 END) AS GUN_0_30,
           SUM(CASE WHEN a.GECIKME_GUN BETWEEN 31 AND 60 THEN a.TL_DEGER ELSE 0 END) AS GUN_31_60,
           SUM(CASE WHEN a.GECIKME_GUN BETWEEN 61 AND 90 THEN a.TL_DEGER ELSE 0 END) AS GUN_61_90,
           SUM(CASE WHEN a.GECIKME_GUN > 90 THEN a.TL_DEGER ELSE 0 END) AS GUN_90_USTU,
           SUM(a.TL_DEGER) AS TOPLAM, COUNT(*) AS KALEM_SAYISI
      FROM :LT_ACIK a
      JOIN KNA1 m ON m.MANDT = '100' AND m.KUNNR = a.MUHATAP
     GROUP BY a.MUHATAP, m.NAME1;
END
-- @@
-- Bank balances: TRY account in local currency (HSL), FX accounts in their own currency (WSL).
CREATE FUNCTION TF_BANKA_BAKIYELERI (IV_TARIH NVARCHAR(8))
RETURNS TABLE (RACCT NVARCHAR(10), TXT50 NVARCHAR(50), PARA NVARCHAR(5), BAKIYE DECIMAL(23,2),
               TL_DEGER DECIMAL(23,2))
LANGUAGE SQLSCRIPT SQL SECURITY INVOKER READS SQL DATA AS
BEGIN
  LT_KUR = SELECT * FROM TF_KUR(:IV_TARIH);
  LT_B =
    SELECT a.RACCT,
           CASE a.RACCT WHEN '1020100001' THEN 'TRY' WHEN '1020200001' THEN 'USD' ELSE 'EUR' END AS PARA,
           SUM(CASE WHEN a.RACCT = '1020100001' THEN a.HSL ELSE a.WSL END) AS BAKIYE
      FROM ACDOCA a
     WHERE a.RCLNT = '100' AND a.RLDNR = '0L' AND a.RBUKRS = '1000'
       AND a.RACCT LIKE '102%' AND a.BUDAT <= :IV_TARIH
     GROUP BY a.RACCT;
  RETURN
    SELECT b.RACCT, t.TXT50, b.PARA, b.BAKIYE, ROUND(b.BAKIYE * r.UKURS, 2) AS TL_DEGER
      FROM :LT_B b
      JOIN :LT_KUR r ON r.FCURR = b.PARA
      JOIN SKAT t ON t.MANDT = '100' AND t.SPRAS = 'T' AND t.KTOPL = 'TDHP' AND t.SAKNR = b.RACCT;
END
