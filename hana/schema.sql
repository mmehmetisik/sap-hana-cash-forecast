--   Functions   TF_KUR = FX rate · TF_ACIK_KALEMLER = open items · TF_ODEME_GECMISI = payment history
--               TF_YASLANDIRMA = aging · TF_BANKA_BAKIYELERI = bank balances
--   Columns     MUHATAP = counterparty · VADE_GUN = payment term (days) · TL_DEGER = value in TRY
--               GECIKME_GUN = days overdue · GECIKME = delay in days · OLAY = event (1 paid, 0 still open)
--               YAS_GUN = days since the due date · VADESI_GELMEMIS = not yet due
--               GUN_0_30 … GUN_90_USTU = 0–30 … over 90 days overdue · TOPLAM = total
--               KALEM_SAYISI = number of items · PARA = currency · BAKIYE = balance · SIRA = rank
--   Parameters  IV_TARIH = report date · IV_GUN = look-back window in days
